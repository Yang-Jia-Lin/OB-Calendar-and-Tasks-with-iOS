import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
const browser = await chromium.launch({ executablePath: process.env.CTT_CHROME || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, timezoneId: 'Asia/Shanghai' });
const page = await context.newPage(), checks = [], errors = [];
page.on('pageerror', e => errors.push(e.message));
const check = (name, value) => { assert.ok(value, name); checks.push(name); };
try {
  await page.goto('http://127.0.0.1:4173');
  await page.getByRole('button', { name: '课题卡片', exact: true }).click();
  const card = page.locator('#research-card');
  // Relevant cover rules observed in Components 3.1.260826: ratio spacer, absolute content, click overlay.
  await page.addStyleTag({ content: await readFile('Tests/fixtures/components-cover.css', 'utf8') });
  await page.evaluate(() => {
    const root = document.querySelector('#research-card'), wrapper = document.createElement('div');
    wrapper.className = 'components--DynamicDataView-PageCard'; wrapper.style.cssText = 'position:fixed;right:20px;top:55px;width:340px;max-width:90vw;z-index:5;background:var(--background-primary)';
    const cover = document.createElement('div'), preview = document.createElement('div');
    cover.className = 'components--DynamicDataView-PageCardCover'; preview.className = 'components--DynamicDataView-PageCardCoverPreviewContent';
    document.body.append(wrapper); wrapper.append(cover); cover.append(preview); preview.append(root); root.removeAttribute('style');
  });
  check('Card displays the existing task title', (await card.textContent()).includes('梳理论文中的核心问题'));
  await page.evaluate(() => { window.cardBubbled = 0; document.body.addEventListener('click', () => window.cardBubbled++); });
  await card.getByRole('button', { name: '开始任务', exact: true }).click();
  await page.waitForFunction(() => window.__preview.controller.state.active);
  const sessionId = await page.evaluate(() => window.__preview.controller.state.active.id);
  check('Card starts the same session shown in the plugin view', (await page.locator('.ctt-current-title').textContent()).includes('梳理论文中的核心问题'));
  check('Card click does not bubble to the parent that opens the note', await page.evaluate(() => window.cardBubbled === 0));
  check('Starting the card creates no duplicate task', await page.evaluate(() => window.__preview.tasks().length === 4));
  check('Native Components cover overlay and ratio spacer do not block controls or crop them', await card.evaluate(e => {
    const cover = e.closest('.components--DynamicDataView-PageCardCover'), preview = e.parentElement, a = e.getBoundingClientRect(), b = preview.getBoundingClientRect();
    return getComputedStyle(cover, '::before').display === 'none' && getComputedStyle(preview, '::after').display === 'none' && a.bottom <= b.bottom;
  }));
  await page.locator('.ctt-timer-controls').getByRole('button', { name: '暂停', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#research-card .ctt-card-status').textContent.includes('已暂停'));
  const paused = await card.locator('.ctt-card-status').textContent();
  await page.waitForTimeout(1200);
  check('Card pause display remains unchanged across a tick', await card.locator('.ctt-card-status').textContent() === paused);
  await card.getByRole('button', { name: '继续', exact: true }).click();
  await page.waitForFunction(() => window.__preview.controller.state.active.runningSince != null);
  check('Card resumes the same session controlled by the plugin', await page.evaluate(id => window.__preview.controller.state.active.id === id, sessionId));
  await card.getByRole('button', { name: '暂停', exact: true }).focus();
  await page.waitForTimeout(1200);
  check('Subscription ticks preserve keyboard focus on the card button', await card.getByRole('button', { name: '暂停', exact: true }).evaluate(e => document.activeElement === e));
  await page.reload(); await page.waitForSelector('.ctt-current-title');
  await page.getByRole('button', { name: '课题卡片', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#research-card .ctt-card-status').textContent.includes('已暂停'));
  check('Reload recovers the same session and task on both surfaces', await page.evaluate(id => window.__preview.controller.state.active.id === id && window.__preview.controller.state.active.task.id === 't1', sessionId));
  await card.getByRole('button', { name: '继续', exact: true }).click();
  await page.waitForTimeout(1100);
  await card.getByRole('button', { name: '结束只记时间', exact: true }).click();
  await page.waitForFunction(() => !window.__preview.controller.state.active);
  check('Record-only finish produces one record and leaves the existing task open', await page.evaluate(id => window.__preview.controller.state.records.filter(r => r.id === id).length === 1 && !window.__preview.tasks().find(t => t.id === 't1').completed, sessionId));
  const stale = await page.evaluate(id => window.__preview.api.pause(id), sessionId);
  check('Old card session is explicitly rejected', !stale.ok && stale.code === 'stale-session');
  await card.getByRole('button', { name: '开始任务', exact: true }).click();
  await page.waitForTimeout(1100);
  await card.getByRole('button', { name: '结束并完成', exact: true }).click();
  await page.waitForFunction(() => document.querySelector('#research-card .ctt-card-status').textContent.includes('任务已完成'));
  check('Explicit completion updates the original task and disables restart', await card.getByRole('button', { name: '开始任务', exact: true }).isDisabled());
  await page.screenshot({ path: '../Agents/Tests/Visuals/21-components-card-shared-session.png', fullPage: true });
  check('Unmount releases the card subscription', await page.evaluate(() => { const p = window.__preview, before = p.api.listeners.size; document.querySelector('#show-card').click(); return p.api.listeners.size === before - 1; }));
  const detached = await page.evaluate(() => {
    const p = window.__preview, root = document.createElement('div'); document.body.append(root);
    const destroy = p.mountTaskCard(root, p.api, p.taskRef(p.tasks()[1]), { source: 'components' });
    p.api.dispose(); const disabled = [...root.querySelectorAll('button')].every(b => b.disabled); destroy(); root.remove(); return disabled;
  });
  check('Plugin unload disables mounted controls and clears subscribers', detached && await page.evaluate(() => window.__preview.api.listeners.size === 0));
  check('No card runtime errors', errors.length === 0);
  await writeFile('../Agents/Tests/card-ui.json', JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
} finally { await browser.close(); }
